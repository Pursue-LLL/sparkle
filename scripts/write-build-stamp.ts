import { execFileSync } from 'child_process'
import fs from 'fs'
import path from 'path'
import { formatSparkleBuildStamp } from './writeBuildStampCore'

/** 读取仓库 git 事实；非 git 仓库或命令失败时返回 unknown，让漂移检测判定为需重建。 */
/** 短 hash 规范化：截断 7 位小写，空值归一 unknown（与 buildDriftPureCore 同规则）。 */
function normalizeCommit(value: string): string {
  const trimmed = value.trim().toLowerCase()
  return trimmed.length === 0 ? 'unknown' : trimmed.slice(0, 7)
}

function readGitFacts(): { commit: string; dirty: boolean } {
  const run = (args: string[]): string => {
    try {
      return execFileSync('git', args, {
        cwd: process.cwd(),
        encoding: 'utf8',
        stdio: ['ignore', 'pipe', 'ignore'],
      }).trim()
    } catch {
      return ''
    }
  }
  return {
    commit: normalizeCommit(run(['rev-parse', 'HEAD'])),
    dirty: run(['status', '--porcelain']).length > 0,
  }
}

const root = process.cwd()
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')) as {
  version: string
}
const stamp = formatSparkleBuildStamp(new Date())
const git = readGitFacts()
const outPath = path.join(root, 'src/shared/buildStamp.ts')
const content = `// Auto-generated by scripts/write-build-stamp.ts — do not edit manually.
export const SPARKLE_BUILD_STAMP = '${stamp}'
export const SPARKLE_SEMVER = '${pkg.version}'
export const SPARKLE_GIT_COMMIT = '${git.commit}'
export const SPARKLE_GIT_DIRTY = ${git.dirty}
`
fs.writeFileSync(outPath, content, 'utf8')
console.log(
  `[write-build-stamp] ${stamp} (semver ${pkg.version}) commit=${git.commit} dirty=${git.dirty ? 1 : 0} → ${outPath}`
)
